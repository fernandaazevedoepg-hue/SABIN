-- SABIN - Modelo dimensional do Data Warehouse (esquema dw)
-- Cria apenas as tabelas, vazias. Os dados são carregados pelo ETL:
-- python -m services.etl_service
-- Correr depois dos scripts de database/relational e database/migrations.

CREATE SCHEMA IF NOT EXISTS dw;
SET search_path TO dw, public;

-- DIMENSÕES
CREATE TABLE dim_data (
  data_key         integer     PRIMARY KEY,
  data             date        NOT NULL UNIQUE,
  dia              integer     NOT NULL,
  mes              integer     NOT NULL,
  nome_mes         varchar(20) NOT NULL,
  trimestre        integer     NOT NULL,
  ano              integer     NOT NULL,
  dia_semana       varchar(20) NOT NULL,
  fim_semana       boolean     NOT NULL,
  dia_semana_num   smallint    GENERATED ALWAYS AS (EXTRACT(isodow FROM data)::smallint) STORED,
  mes_abrev        varchar(3)  GENERATED ALWAYS AS (
    (ARRAY['jan','fev','mar','abr','mai','jun','jul','ago','set','out','nov','dez'])[mes]) STORED,
  trimestre_nome   varchar(2)  GENERATED ALWAYS AS ('T' || trimestre::text) STORED,
  ano_mes          varchar(7)  GENERATED ALWAYS AS (ano::text || '-' || lpad(mes::text, 2, '0')) STORED,
  ano_mes_ordem    integer     GENERATED ALWAYS AS (ano * 100 + mes) STORED,
  semana_iso       smallint    GENERATED ALWAYS AS (EXTRACT(week FROM data)::smallint) STORED,
  dia_do_ano       smallint    GENERATED ALWAYS AS (EXTRACT(doy FROM data)::smallint) STORED,
  primeiro_dia_mes date        GENERATED ALWAYS AS (data - (dia - 1)) STORED
);

CREATE TABLE dim_cliente (
  cliente_key       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id_origem bigint UNIQUE,
  nome_completo     varchar(200) NOT NULL
);

CREATE TABLE dim_livro (
  livro_key       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  livro_id_origem bigint NOT NULL UNIQUE,
  titulo          varchar(255) NOT NULL,
  isbn            varchar(20),
  editora         varchar(150),
  data_publicacao date
);

CREATE TABLE dim_autor (
  autor_key       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  autor_id_origem bigint NOT NULL UNIQUE,
  nome            varchar(150) NOT NULL
);

CREATE TABLE dim_genero (
  genero_key       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  genero_id_origem integer NOT NULL UNIQUE,
  nome             varchar(80) NOT NULL UNIQUE
);

CREATE TABLE dim_pagamento (
  pagamento_key    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  metodo_pagamento varchar(30) NOT NULL UNIQUE
);

-- Dimensões de apoio aos factos de stock e previsão
CREATE TABLE dim_nivel_stock (
  nivel_key    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nivel        varchar(30) NOT NULL UNIQUE,
  recomendacao varchar(60) NOT NULL,
  ordem        smallint    NOT NULL
);

CREATE TABLE dim_modelo_previsao (
  modelo_key smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  modelo     varchar(100) NOT NULL UNIQUE,
  mae        numeric(12,4),
  rmse       numeric(12,4),
  r2         numeric(8,4)
);

CREATE TABLE dim_alerta_previsao (
  alerta_key smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nivel      varchar(20)  NOT NULL,
  tipo       varchar(30)  NOT NULL,
  mensagem   varchar(300) NOT NULL,
  ordem      smallint     NOT NULL,
  UNIQUE (nivel, tipo, mensagem)
);

-- FACT VENDAS
-- Grão: item de venda x autor x género. O valor de cada item reparte-se pelas linhas
-- (peso = 1 / nº autores x nº géneros do livro), por isso as somas nunca duplicam.
CREATE TABLE fact_vendas (
  fact_venda_key       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_key             integer NOT NULL,
  cliente_key          bigint  NOT NULL,
  livro_key            bigint  NOT NULL,
  autor_key            bigint  NOT NULL,
  genero_key           bigint  NOT NULL,
  pagamento_key        bigint  NOT NULL,
  venda_id_origem      bigint  NOT NULL,
  item_venda_id_origem bigint  NOT NULL,
  preco_unitario       numeric(10,2) NOT NULL,
  peso                 numeric NOT NULL,
  quantidade_atribuida numeric NOT NULL,
  receita_atribuida    numeric NOT NULL,
  UNIQUE (item_venda_id_origem, autor_key, genero_key),
  CONSTRAINT fk_fact_data      FOREIGN KEY (data_key)      REFERENCES dim_data(data_key),
  CONSTRAINT fk_fact_cliente   FOREIGN KEY (cliente_key)   REFERENCES dim_cliente(cliente_key),
  CONSTRAINT fk_fact_livro     FOREIGN KEY (livro_key)     REFERENCES dim_livro(livro_key),
  CONSTRAINT fk_fact_autor     FOREIGN KEY (autor_key)     REFERENCES dim_autor(autor_key),
  CONSTRAINT fk_fact_genero    FOREIGN KEY (genero_key)    REFERENCES dim_genero(genero_key),
  CONSTRAINT fk_fact_pagamento FOREIGN KEY (pagamento_key) REFERENCES dim_pagamento(pagamento_key)
);
-- Índices só nas chaves com muita variedade (úteis em DirectQuery quando o facto crescer)
CREATE INDEX idx_fact_vendas_data    ON fact_vendas (data_key);
CREATE INDEX idx_fact_vendas_cliente ON fact_vendas (cliente_key);

-- FACT STOCK
-- Grão: livro x data de referência. Os valores são de um momento: não se somam ao longo do tempo.
CREATE TABLE fact_stock (
  fact_stock_key           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_key                 integer  NOT NULL,
  livro_key                bigint   NOT NULL,
  nivel_key                smallint NOT NULL,
  estoque_atual            integer  NOT NULL,
  qtd_reservada            integer  NOT NULL,
  stock_disponivel         integer  NOT NULL,
  unidades_ultimos_3_meses integer  NOT NULL,
  media_mensal_vendas      numeric(10,2) NOT NULL,
  meses_cobertura          numeric(10,2),
  quantidade_recomendada   integer  NOT NULL,
  preco_venda              numeric(10,2) NOT NULL,
  UNIQUE (data_key, livro_key),
  CONSTRAINT fk_stock_data   FOREIGN KEY (data_key)  REFERENCES dim_data(data_key),
  CONSTRAINT fk_stock_livro  FOREIGN KEY (livro_key) REFERENCES dim_livro(livro_key),
  CONSTRAINT fk_stock_nivel  FOREIGN KEY (nivel_key) REFERENCES dim_nivel_stock(nivel_key)
);

-- FACT PREVISÃO DE RECEITA
-- Grão: mês previsto x modelo. data_key = 1.º dia do mês previsto.
CREATE TABLE fact_previsao (
  fact_previsao_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_key          integer  NOT NULL,
  modelo_key        smallint NOT NULL,
  receita_prevista  numeric(12,2) NOT NULL,
  UNIQUE (data_key, modelo_key),
  CONSTRAINT fk_previsao_data   FOREIGN KEY (data_key)   REFERENCES dim_data(data_key),
  CONSTRAINT fk_previsao_modelo FOREIGN KEY (modelo_key) REFERENCES dim_modelo_previsao(modelo_key)
);

-- FACT ALERTAS DE PREVISÃO
-- Grão: mês do alerta x modelo x alerta. data_key = 1.º dia do mês a que o alerta se refere.
CREATE TABLE fact_alerta_previsao (
  fact_alerta_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_key         integer  NOT NULL,
  modelo_key       smallint NOT NULL,
  alerta_key       smallint NOT NULL,
  variacao_percent numeric(8,2),
  UNIQUE (data_key, modelo_key, alerta_key),
  CONSTRAINT fk_alerta_data   FOREIGN KEY (data_key)   REFERENCES dim_data(data_key),
  CONSTRAINT fk_alerta_modelo FOREIGN KEY (modelo_key) REFERENCES dim_modelo_previsao(modelo_key),
  CONSTRAINT fk_alerta_alerta FOREIGN KEY (alerta_key) REFERENCES dim_alerta_previsao(alerta_key)
);
